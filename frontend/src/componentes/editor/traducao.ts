export const traducao: Translation = (chave, padrao, interpolacoes) => {
  let texto = rotulos[chave] ?? padrao;
  for (const [nome, valor] of Object.entries(interpolacoes ?? {})) texto = texto.replace(`{{${nome}}}`, String(valor));
  return texto;
};
